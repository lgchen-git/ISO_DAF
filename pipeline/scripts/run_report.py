#!/usr/bin/env python3
"""Render the offline pipeline execution report for the layout smoke path."""

from __future__ import annotations

import argparse
import csv
import html
from pathlib import Path

import yaml

from restyle_fiberhmm_report_with_zoom_template import render_existing_run


def render_real_report(config: dict, project_root: Path, output: Path) -> None:
    """Render the real run using the previous customer-facing zoom template."""
    run_root = project_root / "outputs" / str(config.get("run_id", "run001"))
    template = Path(config["report"]["template_html"])
    if not template.is_file():
        raise FileNotFoundError(f"zoom report template is missing: {template}")
    render_existing_run(template, run_root / "06_fiberhmm", output, output.name)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--configfile", required=True, type=Path)
    parser.add_argument("--project-root", required=True, type=Path)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--tmp", required=True, type=Path)
    args = parser.parse_args()
    config = yaml.safe_load(args.configfile.read_text(encoding="utf-8")) or {}
    run_id = str(config.get("run_id", "run001"))
    profile = str(config.get("profile", "unknown"))
    if profile == "qitan_v2_11" and str(config.get("execution", {}).get("mode")) == "real":
        render_real_report(config, args.project_root, args.output)
        return 0
    run_root = args.output.parent.parent
    markers = []
    for marker in sorted(run_root.glob("*/stage_complete.tsv")):
        with marker.open(encoding="utf-8", newline="") as handle:
            rows = {row["field"]: row["value"] for row in csv.DictReader(handle, delimiter="\t")}
        markers.append((marker.parent.name, rows))
    items = "".join(
        f"<tr><td>{html.escape(name)}</td><td>{html.escape(rows.get('status', ''))}</td>"
        f"<td>{html.escape(rows.get('execution_mode', ''))}</td></tr>"
        for name, rows in markers
    )
    title = "ISO_DAF pipeline execution report"
    note = (
        "This report confirms the standardized Snakemake layout and stage artifacts. "
        "It is not a substitute for a completed scientific Qitan analysis run."
        if profile == "qitan_v2_11"
        else "This report is generated by the minimal offline smoke profile."
    )
    document = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title>
<style>body{{font-family:Arial,sans-serif;max-width:960px;margin:40px auto;padding:0 24px;color:#253044}}h1{{color:#1d4e89}}table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #d9e0ea;padding:8px;text-align:left}}th{{background:#eef4fb}}.note{{background:#fff6df;border-left:4px solid #e6a700;padding:12px}}</style></head>
<body><h1>{html.escape(title)}</h1><p><b>Run:</b> {html.escape(run_id)} &nbsp; <b>Profile:</b> {html.escape(profile)}</p>
<p class="note">{html.escape(note)}</p><h2>Stage status</h2><table><thead><tr><th>Stage</th><th>Status</th><th>Execution mode</th></tr></thead><tbody>{items}</tbody></table>
<p>All retained report artifacts belong under <code>outputs/{html.escape(run_id)}</code>; logs belong under <code>log/{html.escape(run_id)}</code>; transient files belong under <code>tmp/{html.escape(run_id)}</code>.</p>
</body></html>"""
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(document, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
